// Turns design/tokens.json into app/lib/ui/tokens.dart and checks that web/src/styles.css uses the same colours.
// Run from the repo root: node design/build.ts. Exits 1 if the web and the tokens disagree.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type Curve = string | number[];
type Tokens = {
  color: { light: Record<string, string>; dark: Record<string, string>; shared: Record<string, string>; mark: Record<string, string> };
  radius: Record<string, number>;
  size: Record<string, number>;
  font: { sans: string[]; mono: string[]; size: Record<string, number> };
  shadow: Record<"light" | "dark", Record<string, number[][]>>;
  motion: Record<string, { ms: number; curve?: Curve; [extra: string]: number | Curve | undefined }>;
};

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8")) as Tokens;
const isToken = (key: string): boolean => !key.startsWith("$");

const camel = (name: string): string => name.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
const pascal = (name: string): string => camel(name).replace(/^./, (c) => c.toUpperCase());
const full = (hex: string): string => {
  const h = hex.toLowerCase().replace("#", "");
  return h.length === 3 ? [...h].map((c) => c + c).join("") : h;
};
// #rrggbb or #rrggbbaa to Flutter's 0xAARRGGBB.
const dartColor = (hex: string): string => {
  const h = full(hex);
  const alpha = h.length === 8 ? h.slice(6) : "ff";
  return `Color(0x${(alpha + h.slice(0, 6)).toUpperCase()})`;
};
const dartCurve = (curve: Curve | undefined): string => {
  if (Array.isArray(curve)) return `Cubic(${curve.join(", ")})`;
  return { "ease-out": "Curves.easeOut", "ease-in-out": "Curves.easeInOut", linear: "Curves.linear" }[curve ?? "linear"] ?? "Curves.linear";
};
const num = (n: number): string => (Number.isInteger(n) ? `${n}.0` : `${n}`);

// Theme colours: light and dark have the same names.
const names = Object.keys(tokens.color.light).filter(isToken);
const fields = names.map((n) => `  final Color ${camel(n)};`).join("\n");
const ctor = names.map((n) => `required this.${camel(n)}`).join(", ");
const values = (set: Record<string, string>) => names.map((n) => `    ${camel(n)}: ${dartColor(set[n]!)},`).join("\n");

const shadows = (Object.keys(tokens.shadow) as ("light" | "dark")[])
  .flatMap((theme) =>
    Object.entries(tokens.shadow[theme]).map(([name, layers]) => {
      const list = layers
        .map(([x, y, blur, spread, alpha]) => {
          const a = Math.round(alpha! * 255).toString(16).padStart(2, "0").toUpperCase();
          return `BoxShadow(color: Color(0x${a}000000), offset: Offset(${num(x!)}, ${num(y!)}), blurRadius: ${num(blur!)}, spreadRadius: ${num(spread!)})`;
        })
        .join(", ");
      return `  static const shadow${pascal(name)}${pascal(theme)} = <BoxShadow>[${list}];`;
    }),
  )
  .join("\n");

const motion = Object.entries(tokens.motion)
  .flatMap(([name, m]) => {
    const id = camel(name);
    const lines = [`  static const ${id} = Duration(milliseconds: ${m.ms});`];
    if (m.curve !== undefined) lines.push(`  static const ${id}Curve = ${dartCurve(m.curve)};`);
    for (const [key, value] of Object.entries(m)) {
      if (key === "ms" || key === "curve" || typeof value !== "number") continue;
      lines.push(key === "delay" ? `  static const ${id}Delay = Duration(milliseconds: ${value});` : `  static const ${id}${pascal(key)} = ${num(value)};`);
    }
    return lines;
  })
  .join("\n");

const group = (prefix: string, record: Record<string, number>) =>
  Object.entries(record)
    .filter(([k]) => isToken(k))
    .map(([k, v]) => `  static const ${prefix}${pascal(k)} = ${num(v)};`)
    .join("\n");
const colorConsts = (record: Record<string, string>) =>
  Object.entries(record)
    .filter(([k]) => isToken(k))
    .map(([k, v]) => `  static const ${camel(k)} = ${dartColor(v)};`)
    .join("\n");

const dart = `// GENERATED by design/build.ts from design/tokens.json. Do not edit by hand:
// change the JSON and run \`node design/build.ts\` from the repo root.

import 'package:flutter/material.dart';

/// The colours that change with the theme, read in widgets with \`context.sk\`.
@immutable
class SkColors extends ThemeExtension<SkColors> {
  const SkColors({${ctor}});

${fields}

  static const light = SkColors(
${values(tokens.color.light)}
  );

  static const dark = SkColors(
${values(tokens.color.dark)}
  );

  @override
  SkColors copyWith({${names.map((n) => `Color? ${camel(n)}`).join(", ")}}) => SkColors(
${names.map((n) => `        ${camel(n)}: ${camel(n)} ?? this.${camel(n)},`).join("\n")}
      );

  @override
  SkColors lerp(SkColors? other, double t) => other == null
      ? this
      : SkColors(
${names.map((n) => `          ${camel(n)}: Color.lerp(${camel(n)}, other.${camel(n)}, t)!,`).join("\n")}
        );
}

/// Everything that does not change with the theme.
abstract final class SkTokens {
${colorConsts(tokens.color.shared)}
${colorConsts(tokens.color.mark)}

${group("radius", tokens.radius)}

${group("size", tokens.size)}

  static const fontSans = <String>[${tokens.font.sans.map((f) => `'${f}'`).join(", ")}];
  static const fontMono = <String>[${tokens.font.mono.map((f) => `'${f}'`).join(", ")}];
${group("text", tokens.font.size)}

${shadows}

${motion}
}
`;
writeFileSync(join(root, "app/lib/ui/tokens.dart"), dart);
console.log("wrote app/lib/ui/tokens.dart");

// The web keeps its own CSS; this only checks that it says the same thing.
const css = readFileSync(join(root, "web/src/styles.css"), "utf8");
const block = (selector: RegExp): Record<string, string> => {
  const start = css.search(selector);
  if (start < 0) throw new Error(`styles.css has no block matching ${selector}`);
  const body = css.slice(css.indexOf("{", start) + 1, css.indexOf("}", start));
  return Object.fromEntries([...body.matchAll(/--([\w-]+):\s*(#[0-9a-fA-F]{3,8})\s*;/g)].map((m) => [m[1]!, full(m[2]!)]));
};
const light = block(/^:root \{/m);
const dark = { ...light, ...block(/^:root\[data-theme="dark"\],\s*\n\.dark \{/m) };
const problems: string[] = [];
const compare = (theme: string, expected: Record<string, string>, actual: Record<string, string>) => {
  for (const [name, value] of Object.entries(expected)) {
    if (!isToken(name)) continue;
    if (actual[name] === undefined) problems.push(`${theme}: --${name} is missing in styles.css`);
    else if (actual[name] !== full(value)) problems.push(`${theme}: --${name} is #${actual[name]} in styles.css, #${full(value)} in tokens.json`);
  }
};
compare("light", tokens.color.light, light);
compare("dark", tokens.color.dark, dark);
compare("shared", tokens.color.shared, light);
if (problems.length) {
  console.error(`web/src/styles.css disagrees with design/tokens.json:\n  ${problems.join("\n  ")}`);
  process.exit(1);
}
console.log(`web/src/styles.css matches all ${names.length * 2 + Object.keys(tokens.color.shared).length} colour tokens`);
